#!/usr/bin/env python3
"""Ablation: turn off quote verification and/or the fail-safe and re-score.

Variants are selected through the TRIAGE_ABLATE environment variable (see preop_triage/config.py)
and evaluated on two sets:
  - the 50 labelled sample cases (expected = human labels)
  - the perturbation suite from eval/perturb.py (expected by construction; text mutations are
    included only when their LLM responses are already cached)

Writes results/ablation.md and results/ablation.json. Replays the committed cache; no API key needed.

    uv run eval/ablation.py        # or: make ablation
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "eval"))

import perturb  # noqa: E402

from core import triage_submission  # noqa: E402

VARIANTS: dict[str, str] = {
    "full pipeline": "",
    "no quote verification": "no_verify",
    "no fail-safe": "no_failsafe",
    "neither": "no_verify,no_failsafe",
}


def score(items: list[tuple[str, dict, str, list[str]]], model: str) -> dict:
    """items: (id, submission, expected_decision, expected_categories)."""
    n = dec = cats = both = 0
    false_ready: list[str] = []
    unavailable = 0
    for cid, sub, exp_dec, exp_cats in items:
        p = triage_submission(sub, model=model)
        if p.meta.llm_failures:
            unavailable += 1
            continue
        n += 1
        actual_cats = sorted({i.category for i in p.issues})
        d, c = p.decision == exp_dec, actual_cats == sorted(exp_cats)
        dec += d
        cats += c
        both += d and c
        if p.decision == "READY" and exp_dec != "READY":
            false_ready.append(cid)
    pct = lambda x: round(100.0 * x / n, 1) if n else None  # noqa: E731
    return {
        "n": n,
        "unavailable": unavailable,
        "decision_acc_pct": pct(dec),
        "categories_acc_pct": pct(cats),
        "harness_aggregate_pct": round(100.0 * (n + dec + cats) / (3 * n), 1)
        if n
        else None,  # json_schema_valid is always true here
        "exact_pct": pct(both),
        "false_ready": false_ready,
    }


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--input", default=str(ROOT / "data" / "patients_sample_50.jsonl"))
    ap.add_argument("--model", default=perturb.DEFAULT_MODEL)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--max-per-family", type=int, default=6)
    ap.add_argument("--out-md", default=str(ROOT / "results" / "ablation.md"))
    ap.add_argument("--out-json", default=str(ROOT / "results" / "ablation.json"))
    args = ap.parse_args()

    if os.environ.get("TRIAGE_ABLATE"):
        raise SystemExit("unset TRIAGE_ABLATE before running the ablation; the runner sets it per variant")

    rows = [json.loads(line) for line in Path(args.input).read_text().splitlines() if line.strip()]
    sample = [(r["case_id"], r["submission"], r["label"]["decision"], r["label"]["categories"]) for r in rows]
    bases = perturb.load_bases(Path(args.input), args.model)
    muts = perturb.generate(bases, args.seed, args.max_per_family)
    # keep only mutations whose LLM responses are available (full-pipeline pass decides)
    usable = []
    for m in muts:
        p = triage_submission(m.submission, model=args.model)
        if not p.meta.llm_failures:
            usable.append(
                (f"{m.family}/{m.name}@{m.base_case}", m.submission, m.expected_decision, m.expected_categories)
            )
    skipped = len(muts) - len(usable)

    results: dict[str, dict] = {}
    for label, flags in VARIANTS.items():
        os.environ["TRIAGE_ABLATE"] = flags
        results[label] = {
            "flags": flags,
            "sample": score(sample, args.model),
            "perturbation": score(usable, args.model),
        }
        print(
            f"{label:24s} sample {results[label]['sample']['harness_aggregate_pct']}%  false READY {len(results[label]['sample']['false_ready'])} | "
            f"perturbation {results[label]['perturbation']['harness_aggregate_pct']}%  false READY {len(results[label]['perturbation']['false_ready'])}"
        )
    os.environ.pop("TRIAGE_ABLATE", None)

    L = [
        "# Ablation",
        "",
        f"Generated by `eval/ablation.py --seed {args.seed}` (model `{args.model}`), replayed from the committed cache.",
        "Variants are switched with `TRIAGE_ABLATE` (`preop_triage/config.py`):",
        "`no_verify` accepts every LLM quote without checking it against the document (and skips the repair retry);",
        "`no_failsafe` lets UNKNOWN checks through (they no longer block clearance or raise MISSING_REQUIRED_DATA).",
        "",
        f"Sets: the 50 labelled sample cases, and {len(usable)} perturbation mutations from `eval/perturb.py`"
        + (f" ({skipped} text mutations skipped: responses not cached)" if skipped else "")
        + ". Accuracy = the harness aggregate (schema valid, decision match, category-set match, equally weighted).",
        "",
        "| variant | sample accuracy | sample decision | sample false READYs | perturbation accuracy | perturbation decision | perturbation false READYs |",
        "|---|---|---|---|---|---|---|",
    ]
    for label, r in results.items():
        s, p = r["sample"], r["perturbation"]
        L.append(
            f"| {label} | {s['harness_aggregate_pct']}% | {s['decision_acc_pct']}% | {len(s['false_ready'])} | "
            f"{p['harness_aggregate_pct']}% | {p['decision_acc_pct']}% | {len(p['false_ready'])} |"
        )
    L += ["", "## False READYs by variant", ""]
    for label, r in results.items():
        fr = r["sample"]["false_ready"] + r["perturbation"]["false_ready"]
        L.append(f"- **{label}:** " + (", ".join(fr) if fr else "none"))
    L.append("")
    Path(args.out_md).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out_md).write_text("\n".join(L))
    Path(args.out_json).write_text(
        json.dumps(
            {
                "seed": args.seed,
                "model": args.model,
                "perturbations_used": len(usable),
                "perturbations_skipped": skipped,
                "variants": results,
            },
            indent=1,
        )
    )
    print("\n".join(L))
    print(f"wrote {args.out_md} and {args.out_json}")


if __name__ == "__main__":
    main()
