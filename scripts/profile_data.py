#!/usr/bin/env python3
"""Profile the sample dataset so the pipeline is designed against real data.

Usage: python3 scripts/profile_data.py [input.jsonl] [output.md]
No LLM calls; stdlib only.
"""
from __future__ import annotations

import json
import re
import statistics
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
inp = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "data" / "patients_sample_50.jsonl"
out = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "notes" / "data_profile.md"

rows = [json.loads(l) for l in inp.read_text().splitlines() if l.strip()]
subs = [r["submission"] for r in rows]
L: list[str] = []
p = L.append


def counter_table(title: str, c: Counter, limit: int = 200) -> None:
    p(f"\n### {title}\n")
    p("| value | n |\n|---|---|")
    for k, v in c.most_common(limit):
        p(f"| `{k}` | {v} |")


p(f"# Data profile: `{inp.name}`\n")
p(f"Records: {len(rows)}. Generated by `scripts/profile_data.py`.\n")

# ---- labels
p("## Labels\n")
counter_table("label.decision", Counter(r["label"]["decision"] for r in rows))
counter_table("label.categories (as a set)", Counter("|".join(sorted(r["label"]["categories"])) or "(none)" for r in rows))
cat_count = Counter(c for r in rows for c in r["label"]["categories"])
counter_table("label category frequency", cat_count)

# ---- top-level / procedure fields
p("\n## Field presence\n")
p("| field | present (non-null) | null | missing key |\n|---|---|---|---|")


def presence(getter, name):
    present = null = missing = 0
    for s in subs:
        try:
            v = getter(s)
        except (KeyError, TypeError):
            missing += 1
            continue
        if v is None:
            null += 1
        else:
            present += 1
    p(f"| `{name}` | {present} | {null} | {missing} |")


for f in ["procedure_type", "procedure_risk", "procedure_date", "is_elective", "location", "case_id"]:
    presence(lambda s, f=f: s["procedure"][f], f"procedure.{f}")
presence(lambda s: s["metadata"]["submission_received_at"], "metadata.submission_received_at")
presence(lambda s: s["patient"]["dob"], "patient.dob")
for f in ["vitals", "labs", "medications", "conditions", "documents"]:
    p(f"| `{f}` (list len) | min {min(len(s.get(f) or []) for s in subs)} / median {statistics.median(len(s.get(f) or []) for s in subs)} / max {max(len(s.get(f) or []) for s in subs)} | empty: {sum(1 for s in subs if not s.get(f))} | |")

counter_table("procedure_risk values", Counter(str(s["procedure"].get("procedure_risk")) for s in subs))
counter_table("procedure_type values", Counter(str(s["procedure"].get("procedure_type")) for s in subs))
counter_table("procedure_date formats (regex class)", Counter(
    re.sub(r"\d", "d", str(s["procedure"].get("procedure_date"))) for s in subs))
counter_table("submission_received_at formats", Counter(
    re.sub(r"\d", "d", str((s.get("metadata") or {}).get("submission_received_at"))) for s in subs))

# received_at vs procedure_date
deltas = []
for s in subs:
    pd_, ra = s["procedure"].get("procedure_date"), (s.get("metadata") or {}).get("submission_received_at")
    if pd_ and ra:
        from datetime import date
        d1 = date.fromisoformat(pd_[:10]); d2 = date.fromisoformat(ra[:10])
        deltas.append((d1 - d2).days)
counter_table("procedure_date minus submission_received_at (days)", Counter(deltas))

# ---- vitals
p("\n## Vitals\n")
vt = Counter(); vkeys = Counter(); vdate = Counter(); vsrc = Counter()
for s in subs:
    for v in s.get("vitals") or []:
        vt[str(v.get("type"))] += 1
        vkeys[(str(v.get("type")), "|".join(sorted(k for k in v if k not in ("type",))))] += 1
        vdate[re.sub(r"\d", "d", str(v.get("date")))] += 1
        vsrc[str(v.get("source"))] += 1
counter_table("vital type", vt)
counter_table("vital type -> keys", Counter({f"{k[0]}: {k[1]}": n for k, n in vkeys.items()}))
counter_table("vital date formats", vdate)
counter_table("vital source", vsrc)
p(f"\nCases with no structured BP: {sum(1 for s in subs if not any(v.get('type')=='blood_pressure' for v in s.get('vitals') or []))}")
p(f"Cases with no structured temperature: {sum(1 for s in subs if not any(v.get('type')=='temperature' for v in s.get('vitals') or []))}")
p(f"Cases with vitals not in chronological order: {sum(1 for s in subs if [v.get('date') for v in s.get('vitals') or []] != sorted(v.get('date') for v in s.get('vitals') or []))}")
dup_ts = 0
for s in subs:
    c = Counter((v.get('type'), v.get('date')) for v in s.get('vitals') or [])
    dup_ts += sum(1 for k, n in c.items() if n > 1)
p(f"Same-type same-timestamp structured vital pairs: {dup_ts}")

# ---- labs
p("\n## Labs\n")
lc = Counter(); ld = Counter(); ls = Counter(); lsrc = Counter(); ldate = Counter(); lkeys = Counter()
for s in subs:
    for l in s.get("labs") or []:
        lc[str(l.get("code"))] += 1
        ld[f"{l.get('code')} :: {l.get('display')}"] += 1
        ls[str(l.get("status"))] += 1
        lsrc[str(l.get("source"))] += 1
        ldate[re.sub(r"\d", "d", str(l.get("effective_at")))] += 1
        lkeys["|".join(sorted(l.keys()))] += 1
counter_table("lab code", lc)
counter_table("lab code :: display", ld)
counter_table("lab status", ls)
counter_table("lab keys", lkeys)
counter_table("lab effective_at formats", ldate)
counter_table("lab source", lsrc)
p(f"\nLabs carry no values (keys above): rule 2 is about presence/recency only.")

# ---- medications
p("\n## Medications\n")
mn = Counter(); ma = Counter(); mkeys = Counter()
for s in subs:
    for m in s.get("medications") or []:
        mn[str(m.get("name"))] += 1
        ma[str(m.get("active"))] += 1
        mkeys["|".join(sorted(m.keys()))] += 1
counter_table("medication.active", ma)
counter_table("medication keys", mkeys)
counter_table("medication name", mn)

# ---- conditions
cn = Counter(str(c.get("name")) for s in subs for c in s.get("conditions") or [])
counter_table("conditions", cn)

# ---- documents
p("\n## Documents\n")
dt = Counter(); ddate = Counter(); dlen = []; dkeys = Counter()
per_case_types = []
for s in subs:
    types = []
    for d in s.get("documents") or []:
        dt[str(d.get("type"))] += 1
        ddate[re.sub(r"\d", "d", str(d.get("date")))] += 1
        dlen.append(len(d.get("text") or ""))
        dkeys["|".join(sorted(d.keys()))] += 1
        types.append(str(d.get("type")))
    per_case_types.append(types)
counter_table("document type (raw field)", dt)
counter_table("document date formats", ddate)
counter_table("document keys", dkeys)
p(f"\nDocument text length (chars): min {min(dlen)}, median {statistics.median(dlen)}, p90 {sorted(dlen)[int(len(dlen)*0.9)]}, max {max(dlen)}; total {sum(dlen)}")
p(f"Documents per case: min {min(map(len, per_case_types))}, max {max(map(len, per_case_types))}")

# text-pattern scan: which facts live only in text
p("\n### Free-text pattern scan (regex, approximate)\n")
pats = {
    "temperature in text (F)": r"\b(9[6-9]|10[0-9])\.\d\s*°?\s*F\b",
    "temperature in text (C)": r"\b3[5-9]\.\d\s*°?\s*C\b|\b3[5-9]\.\d\s*C\b|Temp[^\n]{0,20}\b3[5-9]\.\d",
    "BP in text (nnn/nn)": r"\b(1[0-9]{2}|[89][0-9]|2[0-4][0-9])\s*/\s*(1[0-3][0-9]|[4-9][0-9])\b",
    "'see flowsheet'": r"see flowsheet",
    "procedure date in text": r"(Procedure date|surgery date|scheduled for|date of surgery|Planned procedure date)[^\n]{0,60}",
    "'pending' near signature/consent": r"(signature[^\n]{0,40}pending|pending[^\n]{0,40}signature|NOT COMPLETED|not yet signed|not yet completed|printed for (the patient|her|him|review))",
    "'retained for'/prior H&P": r"(retained for|prior (pre-op )?H&P|longitudinal)",
    "H&P text markers": r"(HISTORY AND PHYSICAL|History and Physical|H&P|Pyhsical)",
    "anticoag brand/generic mention": r"\b(Xarelto|rivaroxaban|Eliquis|apixaban|Coumadin|warfarin|Pradaxa|dabigatran|Savaysa|edoxaban|Lovenox|enoxaparin|heparin|Arixtra|fondaparinux|Bevyxxa|betrixaban)\b",
    "antiplatelet mention": r"\b(aspirin|ASA 81|clopidogrel|Plavix|ticagrelor|Brilinta|prasugrel)\b",
    "'resume' instruction": r"\bresum(e|ption)\b",
    "'hold'/'stop'/'last dose' instruction": r"\b(hold|stop|last dose|discontinue)\b",
    "'to be determined'/'pending OR'": r"(to be determined|pending OR|TBD)",
    "'not on file'": r"not on file",
}
p("| pattern | documents | cases |\n|---|---|---|")
for name, pat in pats.items():
    rx = re.compile(pat, re.I)
    docs = cases = 0
    for s in subs:
        hit = False
        for d in s.get("documents") or []:
            if rx.search(d.get("text") or ""):
                docs += 1; hit = True
        cases += hit
    p(f"| {name} | {docs} | {cases} |")

# Does doc.type agree with text?
p("\n### Document type vs text heading (first line)\n")
fl = Counter()
for s in subs:
    for d in s.get("documents") or []:
        first = (d.get("text") or "").strip().split("\n", 1)[0][:60]
        fl[f"{d.get('type')} => {first}"] += 1
counter_table("type => first line of text", fl, limit=300)

out.write_text("\n".join(L) + "\n")
print(f"wrote {out}")
