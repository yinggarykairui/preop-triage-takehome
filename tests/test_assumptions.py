"""The assumption list stays in sync with the code and the exported notes."""

from __future__ import annotations

import importlib
from pathlib import Path

from preop_triage.assumptions import ASSUMPTIONS, IMPLEMENTED_IN

ROOT = Path(__file__).resolve().parent.parent


def test_every_assumption_names_code_that_exists():
    assert set(ASSUMPTIONS) == set(IMPLEMENTED_IN)
    for aid, targets in IMPLEMENTED_IN.items():
        assert targets, aid
        for dotted in targets:
            module, _, name = dotted.rpartition(".")
            assert hasattr(importlib.import_module(module), name), f"{aid}: {dotted} does not exist"


def test_assumption_ids_cited_by_checks_exist():
    import inspect

    from preop_triage import rules

    cited = set()
    for line in inspect.getsource(rules).splitlines():
        if "assumptions=" in line:
            cited |= {tok.strip("\"'[], ") for tok in line.split("assumptions=")[1].split("]")[0].split(",")}
    assert cited and cited <= set(ASSUMPTIONS)


def test_notes_assumptions_md_is_current():
    """notes/assumptions.md is generated by `make assumptions`; fail if it drifted from the code."""
    from scripts.export_assumptions import render

    assert (ROOT / "notes" / "assumptions.md").read_text() == render()
